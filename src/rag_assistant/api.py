"""Step 5: the HTTP API (FastAPI).

Endpoints:
  GET  /         a small web page to try the assistant
  GET  /health   for the cloud platform's health check
  POST /search   retrieval only (works without the LLM)
  POST /ask      full answer with citations (needs the LLM: AWS credentials for Bedrock)

Run locally:  uvicorn rag_assistant.api:app --reload
Docs:         http://localhost:8000/docs  (generated by FastAPI)

Every call to /ask and /search writes one JSON line to stdout (see monitoring.py).
"""

from __future__ import annotations

import time
import uuid
from contextlib import asynccontextmanager
from functools import lru_cache
from pathlib import Path

from fastapi import FastAPI, HTTPException, Request
from fastapi.concurrency import run_in_threadpool
from fastapi.responses import HTMLResponse
from pydantic import BaseModel, Field

from rag_assistant.agent import build_graph, run
from rag_assistant.config import ANSWER_MODEL
from rag_assistant.embeddings import embed_query
from rag_assistant.lang import detect_language
from rag_assistant.llm import LLMNotConfigured, get_chat_model, llm_configured
from rag_assistant.monitoring import estimate_cost, log_request
from rag_assistant.retrieve import METHODS, get_retriever, resolve_method

STATIC = Path(__file__).parent / "static"


@asynccontextmanager
async def lifespan(app: FastAPI):
    get_retriever()  # load the index once, at start-up
    embed_query("warm-up")  # load the embedding model now, so the first user does not wait for it
    yield


app = FastAPI(title="FR/EN assistant for French renting and work rules", version="0.1.0", lifespan=lifespan)
LOGGED_PATHS = {"/ask", "/search"}  # not /health: the platform calls it every few seconds


@app.middleware("http")
async def log_each_request(request: Request, call_next):
    """Time every request and write one log line, also when it fails.
    The endpoints add their own details to request.state.log."""
    start = time.perf_counter()
    request_id = request.headers.get("x-request-id") or uuid.uuid4().hex[:12]
    request.state.log = {}
    status = 500  # stays 500 if the endpoint raises an unexpected error
    try:
        response = await call_next(request)
        status = response.status_code
        response.headers["X-Request-ID"] = request_id
        return response
    except Exception as exc:
        request.state.log["error"] = type(exc).__name__
        raise
    finally:
        if request.url.path in LOGGED_PATHS:
            log_request(request_id=request_id, endpoint=request.url.path, status=status,
                        latency_ms=round((time.perf_counter() - start) * 1000), **request.state.log)


class AskRequest(BaseModel):
    question: str = Field(min_length=3, max_length=1000, examples=["How much notice must I give my landlord?"])


class SearchRequest(AskRequest):
    k: int = Field(default=5, ge=1, le=20)
    method: str = Field(default="auto", description=f"one of {METHODS}")


@lru_cache(maxsize=1)
def get_graph():
    return build_graph(get_chat_model(), get_retriever())


@app.get("/", response_class=HTMLResponse)
def home() -> str:
    return (STATIC / "index.html").read_text(encoding="utf-8")


@app.get("/health")
def health() -> dict:
    return {"status": "ok", "llm_configured": llm_configured(), "chunks": len(get_retriever().chunks)}


@app.post("/search")
async def search(req: SearchRequest, request: Request) -> dict:
    if req.method not in METHODS:
        raise HTTPException(422, f"method must be one of {METHODS}")
    results = await run_in_threadpool(get_retriever().search, req.question, req.k, req.method)
    request.state.log.update(
        lang=detect_language(req.question), question_chars=len(req.question), k=req.k,
        retrieval_method=resolve_method(req.question, req.method), n_results=len(results),
        n_pages=len({r["page_id"] for r in results}),
        top_score=round(results[0]["score"], 4) if results else None)
    return {"results": [{k: r[k] for k in ("page_id", "page_title", "section", "url", "score")} | {
        "text": r["text"][:500]} for r in results]}


@app.post("/ask")
async def ask(req: AskRequest, request: Request) -> dict:
    log = request.state.log
    log.update(lang=detect_language(req.question), question_chars=len(req.question), model=ANSWER_MODEL)
    try:
        graph = get_graph()
    except LLMNotConfigured as exc:
        log["error"] = "LLMNotConfigured"
        raise HTTPException(503, str(exc)) from exc
    result = await run_in_threadpool(run, graph, req.question)
    usage = result["usage"]
    log.update(
        translated=result["search_query"] != req.question,
        retrieval_method=resolve_method(result["search_query"]),
        n_pages=len({r["page_id"] for r in result["retrieved"]}),
        top_score=result["retrieved"][0]["score"] if result["retrieved"] else None,
        n_citations=len(result["citations"]), no_citation=not result["citations"],
        tool_calls=len(result["tool_calls"]), answer_chars=len(result["answer"]),
        **usage, est_cost_usd=estimate_cost(usage["input_tokens"], usage["output_tokens"]))
    return result | {"model": ANSWER_MODEL}
